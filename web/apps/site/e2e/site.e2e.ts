test('app screenshots rotate, enlarge, and support keyboard navigation', async ({ page }, info) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { level: 1 })).toContainText('Run your agents')
  await page.evaluate(() => document.fonts.ready)
  const showcase = page.getByRole('region', { name: 'Vibeke screenshots' })
  const orbit = showcase.locator('.client-orbit')
  await expect(orbit).toHaveAttribute('data-active-client', 'electron')
  await expect.poll(() => orbit.locator('img').evaluateAll(images => images.every(image => (image as HTMLImageElement).complete && (image as HTMLImageElement).naturalWidth > 0))).toBe(true)
  await expect(orbit.locator('img')).toHaveCount(3)
  for (const [label, client] of [['Terminal', 'tui'], ['Browser', 'web'], ['Desktop', 'electron']]) {
    await showcase.getByRole('tab', { name: label, exact: true }).click()
    await expect(orbit).toHaveAttribute('data-active-client', client!)
    await expect(orbit.locator(`[data-client="${client}"]`)).toHaveAttribute('data-position', 'front')
    const stage = await orbit.boundingBox()
    const frame = await orbit.locator('[data-position="front"]').boundingBox()
    expect(frame!.y).toBeGreaterThanOrEqual(stage!.y)
    expect(frame!.y + frame!.height).toBeLessThanOrEqual(stage!.y + stage!.height + 1)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await showcase.screenshot({ path: `test-results/showcase-${client}-${info.project.name}.png` })
  }
  const desktop = showcase.getByRole('tab', { name: 'Desktop', exact: true })
  await desktop.press('ArrowRight')
  await expect(showcase.getByRole('tab', { name: 'Browser', exact: true })).toBeFocused()
  await expect(orbit).toHaveAttribute('data-active-client', 'web')
  await page.keyboard.press('Home')
  await expect(orbit).toHaveAttribute('data-active-client', 'tui')
  const enlarge = showcase.getByRole('button', { name: 'View full size' })
  await enlarge.click()
  const dialog = page.getByRole('dialog', { name: 'TUI', exact: true })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('img')).toHaveAttribute('src', '/screenshots/tui.png')
  await expect(dialog.getByRole('button', { name: 'Close screenshot' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(enlarge).toBeFocused()
  await desktop.click()
  await orbit.getByRole('button', { name: 'Enlarge Electron app screenshot' }).click()
  await expect(page.getByRole('dialog', { name: 'Electron app', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Close screenshot' }).click()
  // The site honors reduced-motion settings for the perspective transition.
  expect(await orbit.locator('[data-position="front"]').evaluate(element => getComputedStyle(element).transitionDuration)).toBe('0s')
  await page.getByRole('button', { name: 'Remote', exact: true }).click()
  await expect(page.getByText('Connect to a remote host.')).toBeVisible()
  await page.getByRole('button', { name: 'Local', exact: true }).click()
  await expect(page.getByText('Start a workspace.', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  expect(errors).toEqual([])
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }))
  await page.screenshot({ path: `test-results/home-${info.project.name}.png`, fullPage: true })
})

