test('all documentation routes render directly without broken local links or overflow', async ({ page }, info) => {
  for (const doc of docManifest) {
    const response = await page.goto(`/docs/${doc.slug}`)
    expect(response?.status()).toBe(200)
    await expect(page.getByRole('heading', { level: 1 })).toHaveText(doc.title)
    await expect(page.locator('article')).not.toContainText('{{#include')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    const missingAnchors = await page.locator('nav[aria-label="On this page"] a').evaluateAll(links => links.filter(link => !document.getElementById(decodeURIComponent((link as HTMLAnchorElement).hash.slice(1)))).map(link => link.textContent))
    expect(missingAnchors).toEqual([])
  }
  await page.goto('/docs/quickstart')
  await page.screenshot({ path: `test-results/docs-${info.project.name}.png`, fullPage: true })
})

