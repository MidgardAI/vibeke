test('API methods filter, expand, and copy without breaking the table', async ({ page }, info) => {
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.goto('/docs/api')
  const table = page.getByRole('table', { name: 'API methods' })
  await expect(table.getByRole('columnheader')).toHaveCount(2)
  await expect(table.getByRole('rowheader')).toHaveCount(20)
  const search = page.getByRole('searchbox', { name: 'Find an API method' })
  await search.fill('browser.pane.update')
  const method = table.getByRole('button', { name: 'browser.pane.update' })
  await method.focus()
  await method.press('Enter')
  await expect(method).toHaveAttribute('aria-expanded', 'true')
  const details = page.getByRole('region', { name: 'browser.pane.update details' })
  await expect(details).toContainText('Parameters')
  await expect(details).toContainText('viewport')
  await details.getByRole('button', { name: 'Copy parameters' }).click()
  expect(await page.evaluate(() => navigator.clipboard.readText())).toContain('viewport')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(await table.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  await page.screenshot({ path: `test-results/api-${info.project.name}.png`, fullPage: true })
  await method.click()
  await expect(details).toHaveCount(0)
  await search.fill('does-not-exist')
  await expect(page.getByText('No methods match. Change the search or group.')).toBeVisible()
  await search.fill('')
  await page.getByRole('combobox', { name: 'Method group' }).selectOption('agent')
  for (const name of await table.getByRole('rowheader').allTextContents()) expect(name).toMatch(/^agent\./)
  const catalog = await page.request.get('/api-reference/methods.json')
  expect(catalog.status()).toBe(200)
  expect((await catalog.json()).methods.length).toBeGreaterThan(200)
  const schema = await page.request.get('/api-reference/vibeke-1.schema.json')
  expect(schema.status()).toBe(200)
  expect((await schema.json()).$defs).toBeTruthy()
})


